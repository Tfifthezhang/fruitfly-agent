"""Runtime capabilities consumed by Application and implemented by hosts."""
from __future__ import annotations
from pathlib import Path
from typing import Any, Awaitable, Callable, Mapping, Protocol
from fruitfly_agent.core.data_model import AgentLoopResult, ContextItem, ImageBlock
from fruitfly_agent.core.data_model.media import UserContent
from fruitfly_agent.core.tool_runtime.authorization import AuthorizationPrompt
from fruitfly_agent.interactive.contracts.configuration import ConfigurationController
from fruitfly_agent.interactive.contracts.events import EventSink, FrontendEvent, InteractiveEvent
from fruitfly_agent.interactive.contracts.models import (
    ConversationMessage,
    InteractiveStatus,
    ResumableSession,
)
from fruitfly_agent.interactive.contracts.improvement import ImprovementService
from fruitfly_agent.interactive.contracts.candidates import CandidateActivationService, CandidateService
from fruitfly_agent.interactive.contracts.task_packs import TaskPackService


class RuntimeSession(Protocol):
    """Public conversation and execution operations consumed by Application."""
    @property
    def status(self) -> InteractiveStatus: ...
    @property
    def running(self) -> bool: ...
    def set_event_sink(self, sink: EventSink | None) -> None: ...
    def trace(self, limit: int = 12) -> list[InteractiveEvent]: ...
    def conversation(self) -> tuple[ConversationMessage, ...]: ...
    def canonical_items(self) -> tuple[ContextItem, ...]: ...
    def steer(self, prompt: UserContent) -> bool: ...
    def load_attachment(self, path: str) -> ImageBlock: ...
    def cancel(self) -> bool: ...
    async def submit(self, prompt: UserContent) -> AgentLoopResult: ...


class RuntimeAuthorization(Protocol):
    available: bool
    handler: Callable[[AuthorizationPrompt], Awaitable[str]] | None
    emit: Callable[[FrontendEvent], Awaitable[None]] | None
    pending: AuthorizationPrompt | None
    def respond(self, request_id: str, choice: str) -> bool: ...
    def clear(self) -> None: ...
    def status(self) -> dict[str, int | bool | str]: ...
    async def close(self) -> None: ...


class RuntimeHandle(Protocol):
    """Prepared resource operations, distinct from concrete resource ownership."""
    @property
    def session(self) -> RuntimeSession: ...
    @property
    def manifest(self) -> Mapping[str, Any]: ...
    @property
    def improvement(self) -> ImprovementService | None: ...
    @property
    def candidates(self) -> CandidateService | None: ...
    @property
    def task_packs(self) -> TaskPackService | None: ...
    @property
    def candidate_activation(self) -> CandidateActivationService | None: ...
    @property
    def authorization(self) -> RuntimeAuthorization | None: ...
    @property
    def activate_callback(self) -> Callable[[], None] | None: ...
    async def start(self) -> None: ...
    async def health(self) -> dict[str, Any]: ...
    async def close(self) -> None: ...


class RuntimeFactory(Protocol):
    @property
    def configuration(self) -> ConfigurationController: ...

    async def open(
        self,
        *,
        resume: bool,
        session_path: Path | None,
    ) -> RuntimeHandle: ...

    def reload_configuration(self) -> None: ...

    async def prepare_configuration(self, *, session_path: Path) -> RuntimeHandle:
        """Prepare a draft for the same conversation, committing only on activation."""
        ...

    def new_session_path(self) -> Path: ...

    def resumable_sessions(
        self,
        *,
        current_path: Path,
    ) -> tuple[ResumableSession, ...]: ...

