"""Small configuration operation contracts consumed by host services."""
from typing import Protocol
from .profile import HarnessProfile


class BindingEditor(Protocol):
    @property
    def changed(self) -> bool: ...

    def bind_target(self, kind: str, key: str, reference: str) -> object: ...
    def save(self) -> object: ...
    def reset(self) -> object: ...


class ProfileEditor(BindingEditor, Protocol):
    def profile(self, profile_id: str | None = None) -> HarnessProfile: ...
    def stage_profile(self, profile: HarnessProfile) -> None: ...
