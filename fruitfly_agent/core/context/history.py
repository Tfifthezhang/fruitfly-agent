"""Scoped history/artifact capabilities borrowed by context methods."""
from typing import Any, Protocol


class ContextHistory(Protocol):
    def bind(self, items: Any) -> None: ...
    def put(self, text: str) -> str: ...
    def read(self, reference: str, *, offset: int = 0, limit: int = 12000) -> str: ...
    def search(self, query: str, *, limit: int = 20) -> list[dict]: ...
