"""Frozen Agent source and checked host runtime mounts; no per-trial installation."""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import tempfile
from typing import Any
import zipfile

from eval.installation import SOURCE_FILES, SOURCE_PACKAGES, installation_identity
from .host import HostConfig


def digest(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".write-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(value, handle, indent=2, sort_keys=True)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def tree_identity(root: Path, *, exclude_bytecode: bool = False) -> str:
    """Include link destinations and bytes, excluding generated bytecode only."""
    if not root.exists():
        raise ValueError(f"required runtime path is missing: {root}")
    rows: list[tuple[Any, ...]] = []
    def visit(path: Path, relative: str, ancestors: frozenset[Path]) -> None:
        if exclude_bytecode and (path.name == "__pycache__" or path.suffix in {".pyc", ".pyo"}):
            return
        if path.is_symlink():
            rows.append((relative, "link", os.readlink(path)))
        resolved = path.resolve()
        if path.is_dir():
            if resolved in ancestors:
                raise ValueError(f"runtime directory link cycle: {path}")
            rows.append((relative, "directory", path.stat().st_mode & 0o777))
            for child in sorted(path.iterdir()):
                visit(child, relative + "/" + child.name, ancestors | {resolved})
            return
        if path.is_file():
            hasher = hashlib.sha256()
            with path.open("rb") as handle:
                for block in iter(lambda: handle.read(1024 * 1024), b""):
                    hasher.update(block)
            rows.append((relative, "file", hasher.hexdigest(), path.stat().st_mode & 0o777))
        else:
            raise ValueError(f"unsupported or broken runtime file: {path}")
    visit(root, ".", frozenset())
    return digest(rows)


def source_snapshot(package: Path, target: Path) -> dict[str, Any]:
    identity = installation_identity(package)
    target.mkdir(parents=True)
    if package.is_file():
        with zipfile.ZipFile(package) as archive:
            for name in archive.namelist():
                path = Path(name)
                if (path.parts and path.parts[0] in SOURCE_PACKAGES and path.suffix == ".py"
                        and ".." not in path.parts and not path.is_absolute()):
                    dest = target / path
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    dest.write_bytes(archive.read(name))
                elif (len(path.parts) > 2 and path.parts[0].endswith(".dist-info")
                      and path.parts[1] == "licenses" and not name.endswith("/")
                      and ".." not in path.parts and not path.is_absolute()):
                    dest = target / "licenses" / Path(*path.parts[2:])
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    dest.write_bytes(archive.read(name))
    else:
        for name in SOURCE_FILES:
            shutil.copyfile(package / name, target / name)
        for name in SOURCE_PACKAGES:
            for source in (package / name).rglob("*.py"):
                if "__pycache__" in source.parts or source.is_symlink():
                    continue
                dest = target / source.relative_to(package)
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, dest)
    return identity


def prepare_material(host: HostConfig, package: Path) -> dict[str, Any]:
    """Register an existing complete environment and freeze its Agent source."""
    mounts = [{**m.to_dict(), "sha256": tree_identity(m.source, exclude_bytecode=True),
               "resolved_source": str(m.source.resolve())} for m in host.mounts]
    identity = installation_identity(package)
    key = digest({"host": host.identity(), "mounts": mounts, "installation": identity})
    root = host.cache / "runtimes" / key
    if not root.exists():
        root.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".runtime-", dir=root.parent) as temporary:
            staged = Path(temporary) / "runtime"
            staged.mkdir()
            source_snapshot(package, staged / "source")
            result = {"schema_version": 1, "id": key, "host": host.identity(), "mounts": mounts,
                      "source": str(root / "source"), "source_sha256": tree_identity(staged / "source"),
                      "installation": identity, "python": host.python, "environment": host.runtime_env()}
            write_json(staged / "runtime.json", result)
            try:
                staged.rename(root)
            except FileExistsError:
                pass
    result = json.loads((root / "runtime.json").read_text(encoding="utf-8"))
    check_material(host, result)
    return result


def check_material(host: HostConfig, receipt: dict[str, Any]) -> None:
    if receipt.get("schema_version") != 1 or receipt.get("host") != host.identity():
        raise ValueError("Eval host settings changed; run eval prepare again")
    source = Path(receipt["source"])
    if tree_identity(source) != receipt.get("source_sha256"):
        raise ValueError("prepared Agent source changed; run eval prepare again")
    for mount in receipt["mounts"]:
        path = Path(mount["source"])
        if str(path.resolve()) != mount["resolved_source"] or tree_identity(path, exclude_bytecode=True) != mount["sha256"]:
            raise ValueError(f"prepared runtime changed or a link moved: {path}; run eval prepare again")


def runtime_mounts(receipt: dict[str, Any]) -> list[dict[str, Any]]:
    return [{key: row[key] for key in ("type", "source", "target", "read_only")}
            for row in receipt["mounts"]] + [
        {"type": "bind", "source": receipt["source"],
         "target": "/installed-agent/fruitfly/source", "read_only": True},
    ]


